import os
from pathlib import Path
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Preformatted, Table, TableStyle
from reportlab.lib import colors

from backend.config import settings


def generate_markdown_export(reports: list[dict], project_name: str) -> str:
    """Compile all persona reports into a clean, unified Markdown document."""
    sections = [
        f"# Complete Codebase Documentation: {project_name}\n\n*Generated by Multi-Agent Codebase Analysis & Documentation System*\n"
    ]
    for rep in reports:
        persona_title = rep.get("title", rep.get("persona", "").upper())
        content = rep.get("content_markdown", "")
        sections.append(f"\n\n---\n\n## {persona_title}\n\n{content}")

        # Include diagram snippets if present
        diagrams = rep.get("diagrams_json", [])
        if diagrams:
            sections.append("\n\n### System Diagrams (Mermaid)")
            for d in diagrams:
                sections.append(f"#### {d.get('title')}\n```mermaid\n{d.get('code')}\n```")

    return "\n".join(sections)


def generate_pdf_export(reports: list[dict], project_name: str, output_path: Path) -> Path:
    """Generate a clean, professional PDF document from reports using ReportLab."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    doc = SimpleDocTemplate(
        str(output_path),
        pagesize=letter,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40,
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Heading1"],
        fontSize=20,
        leading=24,
        textColor=colors.HexColor("#1e293b"),
        spaceAfter=15,
    )
    h2_style = ParagraphStyle(
        "DocH2",
        parent=styles["Heading2"],
        fontSize=14,
        leading=18,
        textColor=colors.HexColor("#2563eb"),
        spaceBefore=12,
        spaceAfter=6,
    )
    body_style = ParagraphStyle(
        "DocBody",
        parent=styles["Normal"],
        fontSize=9.5,
        leading=13,
        textColor=colors.HexColor("#334155"),
        spaceAfter=6,
    )
    code_style = ParagraphStyle(
        "DocCode",
        parent=styles["Code"],
        fontSize=8,
        leading=10,
        textColor=colors.HexColor("#0f172a"),
        backColor=colors.HexColor("#f1f5f9"),
    )

    story = []
    # Title Header
    story.append(Paragraph(f"Codebase Documentation: {project_name}", title_style))
    story.append(Paragraph("Multi-Agent Codebase Analysis & Documentation System", body_style))
    story.append(Spacer(1, 15))

    for rep in reports:
        persona_label = rep.get("title", rep.get("persona", "").upper())
        story.append(Paragraph(persona_label, h2_style))
        story.append(Spacer(1, 5))

        content = rep.get("content_markdown", "")
        for line in content.splitlines():
            line = line.strip()
            if not line:
                continue
            if line.startswith("#"):
                clean_heading = line.lstrip("#").strip()
                story.append(Paragraph(f"<b>{clean_heading}</b>", h2_style))
            elif line.startswith(("-", "*", "1.", "2.", "3.")):
                story.append(Paragraph(f"&bull; {line.lstrip('-*0123456789. ')}", body_style))
            else:
                story.append(Paragraph(line.replace("<", "&lt;").replace(">", "&gt;"), body_style))

        # Render diagrams in PDF
        diagrams = rep.get("diagrams_json", [])
        if diagrams:
            story.append(Spacer(1, 10))
            story.append(Paragraph("System Diagrams (Mermaid Specification)", h2_style))
            for d in diagrams:
                story.append(Paragraph(f"<b>{d.get('title')} ({d.get('type')})</b>", body_style))
                story.append(Preformatted(d.get("code", "")[:1200], code_style))
                story.append(Spacer(1, 8))

        story.append(Spacer(1, 15))

    doc.build(story)
    return output_path
